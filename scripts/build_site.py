#!/usr/bin/env python3
"""Build the GitHub Pages site (docs/) from the reports, so every number on the site comes from a file.

Reads:  reports/ribbon_lane_report.json, docs/submissions/*.json, docs/*.md
Writes: docs/index.html, docs/executive-summary.html, docs/results.html, docs/sources.html,
        docs/hypotheses.html, docs/irregularities.html, docs/top-score-analysis.html, docs/run-card.json
"""
from __future__ import annotations

import html
import json
from pathlib import Path

import markdown

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
REP = json.loads((ROOT / "reports" / "ribbon_lane_report.json").read_text())
SUBS = sorted((DOCS / "submissions").glob("*.json"))
SUB = json.loads(SUBS[-1].read_text()) if SUBS else None

CSS = """
body{font-family:system-ui,-apple-system,Segoe UI,Roboto,sans-serif;max-width:980px;margin:0 auto;padding:24px;color:#1b1f24;line-height:1.5}
nav a{margin-right:14px;color:#0a58ca;text-decoration:none}
.banner{border-radius:10px;padding:18px 20px;margin:18px 0}
.ok{background:#e8f5e9;border:2px solid #2e7d32}
.hold{background:#fff8e1;border:2px solid #f9a825}
.neg{background:#ffebee;border:2px solid #c62828}
.btn{display:inline-block;background:#0a58ca;color:#fff;padding:12px 18px;border-radius:8px;text-decoration:none;font-weight:600}
table{border-collapse:collapse;width:100%;margin:12px 0;font-size:14px}
th,td{border:1px solid #d0d7de;padding:6px 8px;text-align:left;vertical-align:top}
th{background:#f6f8fa}
code{background:#f6f8fa;padding:1px 4px;border-radius:4px}
.small{color:#57606a;font-size:13px}
"""

NAV = ('<nav><a href="index.html">Home</a><a href="executive-summary.html">Submit: executive summary</a>'
       '<a href="results.html">Results</a><a href="top-score-analysis.html">0.2778 analysis</a>'
       '<a href="hypotheses.html">Hypotheses</a><a href="irregularities.html">Irregularities</a>'
       '<a href="sources.html">Sources</a><a href="run-card.json">Run card (JSON)</a></nav>')


def page(title: str, body: str) -> str:
    return (f"<!doctype html><html lang='en'><head><meta charset='utf-8'><meta name='viewport' content='width=device-width,initial-scale=1'>"
            f"<title>{html.escape(title)} · 58GEMSDOE</title><style>{CSS}</style></head><body>{NAV}{body}"
            f"<p class='small'>Generated by scripts/build_site.py from reports/ribbon_lane_report.json. "
            f"Local holdout numbers are HOLDOUT-DTI, not organizer scores.</p></body></html>")


def md_to_html(name: str) -> str:
    text = (DOCS / name).read_text()
    return markdown.markdown(text, extensions=["tables"])


def pooled_null_dti() -> float:
    """Pooled DTI of random placement with the same number of dots, from the report's baseline rows."""
    b = REP["holdout"]["baselines"]["null_union_same_size"]
    tp = sum(x["tp"] for x in b)
    fp = sum(x["fp"] for x in b)
    g = REP["holdout"]["withheld_positives_total"]
    return tp / (0.2 * (tp + fp) + 0.8 * g)


def status_banner() -> tuple[str, str]:
    cfg = REP.get("config_selection", {})
    chosen = cfg.get("chosen")
    if SUB and chosen:
        ho = REP["config_selection"]["configurations"][chosen]["holdout"]["pooled_dti"]
        rnd = REP["holdout"]["baselines"]["null_union_same_size"]
        return ("hold", f"<h2>File status: DOWNLOADABLE FOR REVIEW — NOT CLEARED FOR SUBMISSION</h2>"
                f"<p>A file was generated (<code>{html.escape(SUB['file'])}</code>, configuration <b>{chosen}</b>), and it passed the uniqueness gate. "
                f"Its local holdout DTI is <b>{ho:.4f}</b>, which is below the random-placement control for the same number of dots "
                f"(see Results). <b>Do not spend a weekly submission slot on it</b> until the holdout is calibrated against an organizer receipt.</p>"
                f"<p><a class='btn' href='submissions/{html.escape(SUB['file'])}' download>Download GeoTIFF (for review)</a></p>")
    return ("neg", "<h2>File status: NO SUBMISSION FILE IS CLEARED</h2>"
            "<p>The ribbon-lane candidate failed the uniqueness gate for every configuration tested (it duplicates an existing "
            "registry raster), and it also scores below random placement on the local holdout. "
            "No GeoTIFF is offered for download, so nothing can be submitted by mistake. "
            "Next steps are in <a href='hypotheses.html'>Hypotheses</a> and <a href='irregularities.html'>Irregularities</a>.</p>")


def index_html() -> str:
    cls, msg = status_banner()
    h = REP["holdout"]
    ci = h["pooled_dti_ci95_tile_bootstrap"]
    body = (f"<h1>58GEMSDOE — GEMS Prize fault-prediction workspace</h1>"
            f"<p>Honest status page. Everything here is either fetched from a file in this repo, or labelled.</p>"
            f"<div class='banner {cls}'>{msg}</div>"
            f"<h2>Key numbers</h2><table><tr><th>Quantity</th><th>Value</th><th>Evidence class</th></tr>"
            f"<tr><td>Pooled holdout DTI (ribbon lane, triple-line emission)</td><td>{h['pooled_dti']:.4f} (95% CI {ci[0]:.4f}–{ci[1]:.4f}; {h['withheld_positives_total']} withheld positives)</td><td>HOLDOUT-DTI</td></tr>"
            f"<tr><td>Random placement, same dot count (control)</td><td>{pooled_null_dti():.4f}</td><td>HOLDOUT-DTI control</td></tr>"
            f"<tr><td>Competition score of the 0.2778 file</td><td>0.2778</td><td>USER-REPORTED (no receipt)</td></tr>"
            f"<tr><td>Official leaderboard rank-1 (dated snapshot)</td><td>0.3195</td><td>SECOND-HAND (via another repo's ledger); not verified</td></tr>"
            f"</table>"
            f"<h2>Start here</h2><ul>"
            f"<li><a href='executive-summary.html'>Executive summary: how to make a submission</a></li>"
            f"<li><a href='results.html'>Results: σ table, leakage canary, holdout, registry check</a></li>"
            f"<li><a href='top-score-analysis.html'>Why did the 0.2778 file score highest, and can we beat it?</a></li>"
            f"<li><a href='hypotheses.html'>Hypotheses (ranked) and what must be obtained</a></li>"
            f"<li><a href='irregularities.html'>Irregularities for review</a></li>"
            f"<li><a href='sources.html'>Sources with verification levels and links</a></li></ul>")
    return page("Home", body)


def exec_html() -> str:
    cls, msg = status_banner()
    body = (f"<h1>Executive summary — how to submit</h1><div class='banner {cls}'>{msg}</div>"
            "<h2>Current answer: do not submit</h2>"
            "<p>No file from this lane has passed the uniqueness gate or beaten the random-placement control, so there is nothing to upload. "
            "The 0.2778 file is treated as a reference only (see its analysis page); it has not been reproduced.</p>"
            "<h2>Steps if a later file is cleared</h2><ol>"
            "<li>Run <code>scripts/build_site.py</code> after <code>scripts/select_unique_ribbon.py</code> so the file, its checksum and its validator output are linked here.</li>"
            "<li>Run <code>src/gems58/validate.py</code> on the file. Do not proceed unless it passes.</li>"
            "<li>Upload the .tif on the DrivenData submission page, with the name and note from the audit JSON.</li>"
            "<li>Check the competition's submission limits and rules on the official page before uploading.</li></ol>"
            "<h2>Why the upload can fail</h2><ul>"
            "<li><b>“Predicted values must be in range [0, 1]”</b>: any value outside [0,1] inside the scored footprint. The validator enforces this.</li>"
            "<li>Wrong CRS, shape or transform: the validator compares them with <code>sample_submission.tif</code>.</li></ul>"
            "<p class='small'>Metric source: DrivenData page 967, verified only through a search excerpt; see Sources.</p>")
    return page("Executive summary", body)


def results_html() -> str:
    rows = "".join(
        f"<tr><td>{r['ridge_type']}/{r['resolution']}</td><td>{r['block']}</td><td>{r['n_pairs']}</td>"
        f"<td>{(r['sigma68'] or 0):.2f}</td><td>{(r['median_abs'] or 0):.2f}</td><td>{(r['null_sigma68'] or 0):.2f}</td></tr>"
        for r in REP["sigma_table"])
    can = "".join(f"<tr><td>{c['feature']}</td><td>{html.escape(c['description'])}</td><td>{c['auc']:.4f}</td></tr>"
                  for c in sorted(REP["canary"], key=lambda c: -c["auc"])[:8])
    blocks = "".join(f"<tr><td>{b['block']}</td><td>{b['n_truth']}</td><td>{b['dots']}</td><td>{b['dti']:.4f}</td></tr>"
                     for b in REP["holdout"]["per_block"])
    base = "".join(f"<tr><td>{b['block']}</td><td>{b['dti']:.4f}</td></tr>" for b in REP["holdout"]["baselines"]["null_union_same_size"])
    sel = ""
    if "config_selection" in REP:
        cs = REP["config_selection"]
        sel = "".join(
            f"<tr><td>{k}</td><td>{v['holdout']['pooled_dti']:.4f}</td><td>{v['holdout']['dots']}</td>"
            f"<td>{'' if v['max_spearman'] is None else round(v['max_spearman'], 3)}</td>"
            f"<td>{'' if v['max_dot_overlap_3px'] is None else round(v['max_dot_overlap_3px'], 3)}</td>"
            f"<td>{v['rasters_over_70pct']}</td><td>{'PASS' if v['passed_gate_B'] else 'FAIL'}</td></tr>"
            for k, v in cs["configurations"].items())
    body = (f"<h1>Results</h1>"
            f"<h2>1. σ table: across-strike error of geophysics-only ridge candidates</h2>"
            f"<p>σ68 = 68th percentile of |across-strike offset| between candidate pixels (≤10 px away) and the nearest withheld fault segment. "
            f"<code>null_sigma68</code> = same statistic for the same number of random footprint pixels (chance level). "
            f"The brief's assumption (σ ≈ 1–3 px) is not met.</p>"
            f"<table><tr><th>class</th><th>block</th><th>pairs</th><th>σ68 (px)</th><th>median |offset|</th><th>null σ68</th></tr>{rows}</table>"
            f"<h2>2. Leakage canary (each feature alone; AUC for withheld fault pixels vs background)</h2>"
            f"<p>Threshold: AUC &gt; 0.90 means leakage until proven otherwise. Max observed: <b>{REP['canary_max_auc']:.4f}</b>.</p>"
            f"<table><tr><th>feature</th><th>description</th><th>AUC</th></tr>{can}</table>"
            f"<h2>3. Holdout (hide-and-recover, 4 spatial blocks, visible faults masked, 5 px buffer)</h2>"
            f"<table><tr><th>block</th><th>withheld positives</th><th>dots</th><th>DTI (cross-fitted config)</th></tr>{blocks}</table>"
            f"<p>Pooled DTI (cross-fitted): <b>{REP['holdout']['pooled_dti']:.4f}</b>; 95% CI from 2000 tile bootstraps: "
            f"{REP['holdout']['pooled_dti_ci95_tile_bootstrap'][0]:.4f}–{REP['holdout']['pooled_dti_ci95_tile_bootstrap'][1]:.4f}.</p>"
            f"<h3>Random placement, same dot count (control)</h3><table><tr><th>block</th><th>DTI</th></tr>{base}</table>"
            f"<h2>4. Configuration choice and uniqueness gate</h2>"
            f"<table><tr><th>configuration</th><th>pooled holdout DTI</th><th>dots</th><th>max Spearman</th><th>max dot overlap ≤3 px</th><th>rasters &gt;70 %</th><th>gate B</th></tr>{sel}</table>"
            f"<p class='small'>Gate B = Spearman &lt; 0.90 AND dot overlap ≤ 70 % against every single registry raster whose positives are a dot set. "
            f"{REP.get('config_selection', {}).get('multiple_selection_note', '')}</p>")
    return page("Results", body)


def main() -> None:
    (DOCS / "index.html").write_text(index_html())
    (DOCS / "executive-summary.html").write_text(exec_html())
    (DOCS / "results.html").write_text(results_html())
    for md, title, out in [("sources.md", "Sources", "sources.html"), ("hypotheses.md", "Hypotheses", "hypotheses.html"),
                           ("irregularities.md", "Irregularities", "irregularities.html"),
                           ("top-score-analysis.md", "0.2778 analysis", "top-score-analysis.html")]:
        (DOCS / out).write_text(page(title, md_to_html(md)))
    card = dict(
        hypothesis="Geophysics-only ridge candidates, emitted as parallel dotted lines at a sigma-scaled width, "
                   "can place the 0.2778-style dotted emission within ~1 px of hidden faults.",
        mechanism="Ridge filter on 100 m magnetic-edge (band 3) and detrended-elevation (band 12) layers; skeleton; "
                  "parallel offsets along the across-ridge normal; line count chosen by U on calibration blocks.",
        non_fault_mimic="Topographic ridges, lithologic contacts, basin-margin steps and flight-line gridding artefacts.",
        holdout_dti=dict(value=REP["holdout"]["pooled_dti"], ci95=REP["holdout"]["pooled_dti_ci95_tile_bootstrap"],
                         evidence="HOLDOUT-DTI", withheld_positives=REP["holdout"]["withheld_positives_total"],
                         evaluator="gems58.dti (exact; unit-tested against brute force)"),
        random_placement_control_pooled_dti=round(pooled_null_dti(), 5),
        correlation_overlap_vs_registry=REP.get("config_selection", {}).get("chosen") or "gate failed for all configurations; see report",
        raster_sha256=SUB["sha256"] if SUB else None,
        validator_output=SUB["validator"]["checks"] if SUB else None,
        submission_name=SUB["name"] if SUB else None,
        submission_note=(SUB["note"][:140] if SUB else None),
        verdict="negative" if REP["holdout"]["pooled_dti"] < pooled_null_dti() else "hold",
        verdict_reason="holdout DTI below random placement of the same dot count; ribbon sigma (5-8 px) is not the assumed 1-3 px",
        canary_max_auc=REP["canary_max_auc"],
    )
    (DOCS / "run-card.json").write_text(json.dumps(card, indent=1))


if __name__ == "__main__":
    main()
